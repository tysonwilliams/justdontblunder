/**
 * After `expo export -p web`, copy the not-found page to 404.html so a static
 * host can answer unknown paths with status 404. Also check the public files
 * and the legal pages made it into the export.
 */
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const dist = path.resolve('dist');

function fail(message) {
  console.error(message);
  process.exit(1);
}

const notFound = path.join(dist, '+not-found.html');
if (!existsSync(notFound)) fail('missing dist/+not-found.html');
copyFileSync(notFound, path.join(dist, '404.html'));

const required = [
  'index.html',
  'drills.html',
  'learn.html',
  'practice.html',
  'progress.html',
  'account.html',
  'privacy.html',
  'terms.html',
  'delete-account.html',
  '404.html',
  'robots.txt',
  'sitemap.xml',
  'manifest.webmanifest',
  'og.png',
  'apple-touch-icon.png',
  'favicon.png',
  'icon-192.png',
  'icon-512.png',
];

for (const file of required) {
  if (!existsSync(path.join(dist, file))) fail(`missing dist/${file}`);
}

function visible(html) {
  return html.replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, '');
}

function plain(html) {
  return visible(html).replaceAll('&#x27;', "'").replaceAll('&apos;', "'");
}

const indexHtml = readFileSync(path.join(dist, 'index.html'), 'utf8');
const manifestLinks = indexHtml.match(/rel="manifest"/g) ?? [];
if (manifestLinks.length !== 1) {
  fail(`expected exactly 1 manifest link in dist/index.html, found ${manifestLinks.length}`);
}

const privacy = plain(readFileSync(path.join(dist, 'privacy.html'), 'utf8'));
if (!privacy.includes('<title>Privacy · Just Don')) fail('privacy title missing from the static HTML');
if (!privacy.includes("Just Don't Blunder is a chess trainer")) {
  fail('privacy policy text is not in the initial HTML');
}
if (!privacy.includes('client_errors')) fail('privacy page does not disclose client_errors');

const terms = plain(readFileSync(path.join(dist, 'terms.html'), 'utf8'));
if (!terms.includes('<title>Terms · Just Don')) fail('terms title missing from the static HTML');
if (!terms.includes("These terms cover the Just Don't Blunder chess trainer")) {
  fail('terms text is not in the initial HTML');
}

const missing = plain(readFileSync(path.join(dist, '404.html'), 'utf8'));
if (!missing.includes('<title>Page not found · Just Don')) fail('404 title missing from the static HTML');
if (!missing.includes('noindex')) fail('404 page is missing noindex');

const robots = readFileSync(path.join(dist, 'robots.txt'), 'utf8');
if (robots.includes('<div id="root">')) fail('robots.txt is the app shell');
if (!robots.includes('Sitemap: https://justdontblunder.com/sitemap.xml')) fail('robots.txt missing sitemap');

function listUrlsUnder(subDir) {
  const root = path.join(dist, subDir);
  if (!existsSync(root)) return [];
  const urls = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        walk(full);
      } else if (entry.isFile() && !entry.name.endsWith('.map')) {
        const rel = path.relative(dist, full).split(path.sep).join('/');
        urls.push(`/${rel}`);
      }
    }
  };
  walk(root);
  return urls.sort();
}

const coreRoutes = [
  '/',
  '/drills',
  '/learn',
  '/practice',
  '/progress',
  '/manifest.webmanifest',
  '/favicon.png',
  '/apple-touch-icon.png',
  '/icon-192.png',
  '/icon-512.png',
];
const staticAssets = [...listUrlsUnder('_expo/static'), ...listUrlsUnder('assets')];
const precacheUrls = [...coreRoutes, ...staticAssets];
const cacheHash = createHash('sha256').update(precacheUrls.join('\n')).digest('hex').slice(0, 10);
const cacheName = `jdb-v1-${cacheHash}`;

const swSource = `// Generated by scripts/finalize-web-export.mjs
const CACHE_NAME = ${JSON.stringify(cacheName)};
const PRECACHE_URLS = ${JSON.stringify(precacheUrls, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE_NAME)
      .then((cache) => cache.addAll(PRECACHE_URLS))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE_NAME).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname.startsWith('/auth/') || url.pathname === '/account' || url.pathname === '/delete-account') {
    return;
  }

  if (url.pathname.startsWith('/_expo/static/') || url.pathname.startsWith('/assets/')) {
    event.respondWith(
      caches.match(request).then(
        (cached) =>
          cached ||
          fetch(request).then((response) => {
            if (response.ok) {
              const copy = response.clone();
              void caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
            }
            return response;
          }),
      ),
    );
    return;
  }

  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (response.ok) {
            const copy = response.clone();
            void caches.open(CACHE_NAME).then((cache) => cache.put(url.pathname, copy));
          }
          return response;
        })
        .catch(() => caches.match(url.pathname).then((hit) => hit || caches.match('/'))),
    );
    return;
  }

  event.respondWith(
    caches.match(request).then((cached) => {
      const fresh = fetch(request)
        .then((response) => {
          if (response.ok) {
            const copy = response.clone();
            void caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
          }
          return response;
        })
        .catch(() => cached);
      return cached || fresh;
    }),
  );
});
`;

writeFileSync(path.join(dist, 'sw.js'), swSource, 'utf8');

console.log(
  `static export includes 404.html, legal HTML, public files, and sw.js (${cacheName}, ${precacheUrls.length} cached entries)`,
);
