export const PUZZLE_SOURCE = 'beginner-blunders';
export const PUZZLE_LICENSE = 'All rights reserved';

const THEMES = new Set(['hanging', 'fork', 'pin', 'back_rank', 'missed_mate']);
const SQUARE = /^[a-h][1-8]$/;

export type SeedPuzzle = {
  id: string;
  fen: string;
  sideToMove: string;
  theme: string;
  atRiskSquare: string;
  prompt: string;
  solution: unknown;
  acceptable: unknown;
  traps: unknown;
  note: string;
  expectedDropCp: number;
};

/** Idempotent upsert for public.puzzles. The database owner runs it; the anon key cannot. */
export function buildPuzzleSeedSql(puzzles: readonly SeedPuzzle[]): string {
  if (puzzles.length === 0) throw new Error('The starter bank is empty.');
  const seen = new Set<string>();
  const values = puzzles.map((puzzle) => {
    if (seen.has(puzzle.id)) throw new Error(`Duplicate puzzle id ${puzzle.id}`);
    seen.add(puzzle.id);
    assertPuzzle(puzzle);
    return `(${[
      sql(puzzle.id),
      sql(puzzle.fen),
      sql(puzzle.theme),
      sql(puzzle.sideToMove),
      sqlJson(puzzle.traps),
      sql(PUZZLE_SOURCE),
      sql(PUZZLE_LICENSE),
      sql(puzzle.atRiskSquare),
      sql(puzzle.prompt),
      sqlJson(puzzle.solution),
      sqlJson(puzzle.acceptable),
      sql(puzzle.note),
      sqlInt(puzzle.expectedDropCp),
    ].join(', ')})`;
  });
  return `-- Generated by scripts/seed-puzzles.mts.
-- Idempotent upsert of the starter bank (${puzzles.length} positions).
-- Apply as the database owner. Client roles cannot write public.puzzles.
-- Source: ${PUZZLE_SOURCE}. License: ${PUZZLE_LICENSE}.
-- These positions are generated in this repo. They are not from the Lichess puzzle database.

insert into public.puzzles (
  id,
  fen,
  theme,
  side_to_move,
  traps,
  source,
  license,
  at_risk_square,
  prompt,
  solution,
  acceptable,
  note,
  expected_drop_cp
)
values
  ${values.join(',\n  ')}
on conflict (id) do update set
  fen = excluded.fen,
  theme = excluded.theme,
  side_to_move = excluded.side_to_move,
  traps = excluded.traps,
  source = excluded.source,
  license = excluded.license,
  at_risk_square = excluded.at_risk_square,
  prompt = excluded.prompt,
  solution = excluded.solution,
  acceptable = excluded.acceptable,
  note = excluded.note,
  expected_drop_cp = excluded.expected_drop_cp;
`;
}

function assertPuzzle(puzzle: SeedPuzzle): void {
  if (puzzle.id.length < 1 || puzzle.id.length > 64) throw new Error(`Bad puzzle id ${puzzle.id}`);
  if (!THEMES.has(puzzle.theme)) throw new Error(`${puzzle.id} has theme ${puzzle.theme}`);
  if (puzzle.sideToMove !== 'w' && puzzle.sideToMove !== 'b') throw new Error(`${puzzle.id} has no side`);
  if (!SQUARE.test(puzzle.atRiskSquare)) throw new Error(`${puzzle.id} has no square`);
  if (puzzle.fen.length < 15 || puzzle.fen.length > 200) throw new Error(`${puzzle.id} has a bad fen`);
  if (puzzle.prompt.length < 1 || puzzle.prompt.length > 200) throw new Error(`${puzzle.id} has a bad prompt`);
  if (puzzle.note.length < 1 || puzzle.note.length > 500) throw new Error(`${puzzle.id} has a bad note`);
  if (!Array.isArray(puzzle.solution) || !Array.isArray(puzzle.acceptable) || !Array.isArray(puzzle.traps)) {
    throw new Error(`${puzzle.id} is missing move lists`);
  }
  if (!Number.isInteger(puzzle.expectedDropCp)) throw new Error(`${puzzle.id} has a bad drop`);
}

function sql(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

function sqlJson(value: unknown): string {
  return `${sql(JSON.stringify(value))}::jsonb`;
}

function sqlInt(value: number): string {
  return String(value);
}
